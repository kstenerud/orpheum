def git_repo(files: dict[str, str]) -> Path:
    """A throwaway git repository holding `files`, so the gates' `git ls-files` works."""
    root = Path(tempfile.mkdtemp(prefix="gate-test-"))
    for path, text in files.items():
        full = root / path
        full.parent.mkdir(parents=True, exist_ok=True)
        full.write_text(text)
    subprocess.run(["git", "init", "-q"], cwd=root, check=True)
    return root


class SourceHeaders(unittest.TestCase):
    def test_directory_decides_the_licence(self):
        self.assertEqual(cs.required_licence("web/apps/web/src/main.tsx"), "MPL-2.0")
        self.assertEqual(cs.required_licence("internal/core/api/doc.go"), "GPL-3.0-or-later")

    def test_missing_and_wrong_headers_fail(self):
        self.assertIsNotNone(cs.check_header("internal/x.go", "package x\n"))
        wrong = "// SPDX-License-Identifier: MPL-2.0\npackage x\n"
        self.assertIn("requires", cs.check_header("internal/x.go", wrong).message)
        self.assertIsNone(cs.check_header("web/a.ts", "// SPDX-License-Identifier: MPL-2.0\n"))
        html = "<!-- SPDX-License-Identifier: MPL-2.0 -->\n<html>"
        self.assertIsNone(cs.check_header("web/apps/web/index.html", html))

    def test_size_warns_then_fails_and_the_allowlist_needs_a_reason(self):
        big = "x\n" * 801
        mid = "x\n" * 401
        self.assertIsNotNone(cs.check_size("a.go", big, {})[0])
        self.assertIsNotNone(cs.check_size("a.go", mid, {})[1])
        self.assertIsNone(cs.check_size("a.go", big, {"a.go": "one table, split loses it"})[0])
        self.assertIsNotNone(cs.check_size("a.go", big, {"a.go": ""})[0])

    def test_generated_and_exempt_files_are_skipped(self):
        self.assertTrue(cs.is_generated("// Code generated by sqlc. DO NOT EDIT.\npackage x"))
        self.assertFalse(cs.is_source("web/node_modules/x/index.js"))
        self.assertFalse(cs.is_source("docs/contributors/README.md"))
        self.assertTrue(cs.is_source("Makefile"))

    def test_query_files_must_be_ascii(self):
        bad = cs.check_ascii("internal/store/queries/user.sql", "-- ok\n-- see \u00a7 4\n")
        self.assertIn("line 2 column 8", bad.message)
        self.assertIsNone(cs.check_ascii("internal/store/queries/user.sql", "-- see section 4\n"))
        self.assertIsNone(cs.check_ascii("internal/core/x.go", "// \u00a7 4\n"))
        for cache in ("internal/store/cache/queries/job.sql", "internal/store/cache/schema.sql"):
            self.assertIsNotNone(cs.check_ascii(cache, "-- see \u00a7 4\n"), cache)

    def test_whole_tree(self):
        root = git_repo({
            "ok.go": "// SPDX-License-Identifier: GPL-3.0-or-later\npackage ok\n",
            "bad.go": "package bad\n",
        })
        problems, _ = cs.check(root, cs.tracked_files(root))
        self.assertEqual([p.path for p in problems], ["bad.go"])


class Deps(unittest.TestCase):
    GO_MOD = (
        "module example.com/m\n\ngo 1.26\n\n"
        "require golang.org/x/crypto v0.57.0\n\n"
        "require (\n\tgolang.org/x/sys v0.40.0 // indirect\n)\n"
    )

    def test_go_mod_parsing_reads_both_forms(self):
        self.assertEqual(cdeps.go_modules(self.GO_MOD), ["golang.org/x/crypto", "golang.org/x/sys"])

    def test_unlisted_and_reasonless_entries_fail(self):
        root = git_repo({
            "go.mod": self.GO_MOD,
            "deps/go.allow": "golang.org/x/crypto  # argon2id (D194)\ngolang.org/x/sys\n",
            "deps/npm.allow": "react  # UI (D193)\n",
            "web/package.json": json.dumps({"name": "orpheum-web", "devDependencies": {"left-pad": "1.0.0"}}),
            "web/apps/web/package.json": json.dumps({"name": "@orpheum/web",
                                                     "dependencies": {"react": "19.0.0", "orpheum-web": "*"}}),
        })
        problems, _ = cdeps.check(root)
        messages = " | ".join(p.message for p in problems)
        self.assertIn("'golang.org/x/sys' is listed without a reason", messages)
        self.assertIn("'left-pad' is not in deps/npm.allow", messages)
        self.assertNotIn("orpheum-web", messages)  # our own workspace package
        self.assertNotIn("'react' is not", messages)


class Claims(unittest.TestCase):
    def test_arch_citations_must_match_definitions_both_ways(self):
        files = {
            "internal/archtest/arch_test.go": "func TestArch_Defined(t *testing.T) {}\n"
                                              "func TestArch_Uncited(t *testing.T) {}\n",
            "internal/core/doc.go": "// Enforced by TestArch_Defined and TestArch_Imagined.\n",
            "docs/contributors/decisions/working-notes.md": "TestArch_OldHistory\n",
        }
        messages = " | ".join(p.message for p in cc.check_arch(files))
        self.assertIn("`TestArch_Imagined`, which no test defines", messages)
        self.assertIn("`TestArch_Uncited`, which no doc cites", messages)
        self.assertNotIn("TestArch_OldHistory", messages)  # history may cite anything
        self.assertNotIn("TestArch_Defined", messages)

    def test_code_decisions_resolve_and_are_live(self):
        files = {
            "internal/a.go": "// D193: the node does the work. D5 was Postgres. D999 is invented.\n"
                             "var hd = \"1080p HD\"; const x = 0xD1\n",
        }
        problems = cc.check_code_decisions(files, live={193}, archived={5})
        text = " | ".join(p.message for p in problems)
        self.assertIn("D5, which is archived", text)
        self.assertIn("D999, which does not exist", text)
        self.assertEqual(len(problems), 2)

    def test_test_variables_must_be_set_by_a_job(self):
        files = {
            "internal/x_test.go": 'os.Getenv("ORPHEUM_TEST_LANDLOCK"); os.Getenv("ORPHEUM_TEST_GPU")',
            "Makefile": "test-lab: export ORPHEUM_TEST_LANDLOCK := 1\n",
        }
        problems = cc.check_test_vars(files)
        self.assertEqual(len(problems), 1)
        self.assertIn("ORPHEUM_TEST_GPU", problems[0].message)


class TestWeakening(unittest.TestCase):
    def test_removed_test_new_skip_and_fewer_assertions_are_found(self):
        before = ("func TestA(t *testing.T) { t.Fatal(\"x\") }\n"
                  "func TestB(t *testing.T) { t.Error(\"y\"); t.Error(\"z\") }\n")
        after = "func TestB(t *testing.T) { t.Skip(\"later\"); t.Error(\"y\") }\n"
        whats = [w.what for w in tw.compare("x_test.go", before, after)]
        self.assertIn("test 'TestA' was removed", whats)
        self.assertIn("1 new skip/only/todo", whats)
        self.assertIn("assertions went from 3 to 1", whats)

    def test_typescript_cases_and_only(self):
        before = "it('plays', () => { expect(a).toBe(1) })\nit('pauses', () => {})\n"
        after = "it.only('plays', () => { expect(a).toBe(1) })\n"
        whats = [w.what for w in tw.compare("a.test.ts", before, after)]
        self.assertIn("test 'pauses' was removed", whats)
        self.assertIn("1 new skip/only/todo", whats)

    def test_a_new_golden_is_not_weakening_but_a_changed_one_is(self):
        golden = "internal/store/testdata/golden/schema-v0002.sql"
        self.assertIsNone(tw.golden_weakening("A", golden))
        for status in ("M", "D", "R"):
            weakened = tw.golden_weakening(status, golden)
            self.assertIsNotNone(weakened, status)
            self.assertEqual(weakened.path, golden)

    def test_a_stronger_test_is_not_weakening(self):
        before = "func TestA(t *testing.T) { t.Fatal(\"x\") }\n"
        after = before + "func TestB(t *testing.T) { t.Fatal(\"y\") }\n"
        self.assertEqual(tw.compare("x_test.go", before, after), [])


class Generated(unittest.TestCase):
    def test_snapshot_reads_directories_and_single_files(self):
        root = Path(tempfile.mkdtemp(prefix="gen-test-"))
        (root / "gen").mkdir()
        (root / "gen" / "a.go").write_text("a")
        (root / "doc.json").write_text("{}")
        self.assertEqual(cg.snapshot(root, ("gen", "doc.json", "missing")),
                         {"gen/a.go": b"a", "doc.json": b"{}"})

    def test_correct_output_passes_whether_or_not_it_is_staged(self):
        same = {"internal/store/sqlcgen/db.go": b"package sqlcgen\n"}
        self.assertEqual(cg.differences(same, dict(same)), [])

    def test_a_hand_edit_a_new_file_and_a_dropped_file_fail(self):
        before = {"a.go": b"edited by hand\n", "gone.go": b"x"}
        after = {"a.go": b"generated\n", "new.go": b"y"}
        found = cg.differences(before, after)
        self.assertEqual([f for f, _ in found], [
            "a.go:1: differs from what its source generates",
            "gone.go:1: there before, but the generator no longer writes it; delete it",
            "new.go:1: generated, but not there before; commit it",
        ])
        self.assertIn("-edited by hand", found[0][1])
        self.assertIn("+generated", found[0][1])


class RevertRed(unittest.TestCase):
    def test_commit_types(self):
        self.assertEqual(rr.commit_type("fix(scan): keep identity"), "fix")
        self.assertTrue(rr.claims_behavior_change({"feat"}))
        self.assertTrue(rr.claims_behavior_change({None}))  # unparseable owes red
        self.assertFalse(rr.claims_behavior_change({"docs", "refactor"}))

    def test_test_files_and_scopes_per_language(self):
        self.assertTrue(rr.is_test_file("internal/core/x_test.go"))
        self.assertTrue(rr.is_test_file("web/packages/sdk/src/pick.test.ts"))
        self.assertFalse(rr.is_test_file("web/packages/sdk/src/pick.ts"))
        self.assertEqual(rr.scope_for("internal/core/api/x.go"), ["go", "test", "./internal/core/api/..."])
        self.assertEqual(rr.scope_for("web/apps/web/src/App.tsx"), ["npm", "--prefix", "web", "run", "test"])
        self.assertIsNone(rr.scope_for("docs/x.md"))

    def test_files_only_other_builds_compile_are_run_against_those_builds(self):
        dev = rr.other_builds("cmd/orpheum/dev_seed.go")
        self.assertEqual([a.command for a in dev], [["go", "test", "-tags", "dev", "./..."]])
        darwin = rr.other_builds("internal/store/space_darwin.go")
        self.assertEqual(darwin[-1].command, ["go", "vet", "./..."])
        self.assertEqual(darwin[-1].env, {"GOOS": "darwin"})
        self.assertTrue(darwin[-1].compile_only)
        self.assertEqual(len(rr.other_builds("internal/store/space_linux.go")), 1)
        self.assertEqual(rr.other_builds("web/apps/web/src/App.tsx"), [])

    def test_verified_by_needs_a_ticked_queue_item(self):
        root = Path(tempfile.mkdtemp())
        queue = root / rr.VQ_FILE
        queue.parent.mkdir(parents=True)
        queue.write_text("- [x] **VQ1** — film plays on her TV\n- [ ] **VQ2** — not yet\n")
        self.assertEqual(rr.verification_queue_problem("VQ1", str(root)), "")
        self.assertIn("not ticked", rr.verification_queue_problem("VQ2", str(root)))
        self.assertIn("is not in", rr.verification_queue_problem("VQ3", str(root)))
        self.assertIn("names no VQ", rr.verification_queue_problem("ran it by hand", str(root)))


class CommitLint(unittest.TestCase):
    def lint(self, subject: str, body: str = "") -> list[str]:
        return [p.rule for p in lc.lint([lc.Commit("0" * 40, subject, body)])]

    def test_shapes(self):
        self.assertEqual(self.lint("feat(scan): add payload hash", "Why: identity survives tag edits."), [])
        self.assertEqual(self.lint("added stuff"), ["subject-shape"])
        self.assertEqual(self.lint("docs: fix typo."), ["trailing-period"])
        self.assertEqual(self.lint("fix(api): stop leaking tokens"), ["missing-body"])
        self.assertIn("bare-claude-trailer", self.lint("docs: x", "Co-Authored-By: Claude <noreply@anthropic.com>"))

    def test_message_file_form_drops_comments(self):
        c = lc.commit_from_message("# Please enter\nfix(api): stop leaking tokens\n\n# comment\n")
        self.assertEqual(c.subject, "fix(api): stop leaking tokens")
        self.assertEqual([p.rule for p in lc.lint([c])], ["missing-body"])


class SpeculativeApi(unittest.TestCase):
    def test_flagged_everywhere_it_builds_is_speculative(self):
        out = "internal/core/a.go:3:6: func onlyTested is unused (unused)\n"
        flagged = {"linux/amd64": lsa.parse_findings(out), "darwin/arm64": lsa.parse_findings(out)}
        compiled = {"linux/amd64": {"internal/core/a.go"}, "darwin/arm64": {"internal/core/a.go"}}
        self.assertEqual(len(lsa.speculative(flagged, compiled)), 1)
        compiled_linux_only = {"linux/amd64": {"internal/core/a.go"}, "darwin/arm64": set()}
        flagged_linux_only = {"linux/amd64": lsa.parse_findings(out), "darwin/arm64": set()}
        self.assertEqual(len(lsa.speculative(flagged_linux_only, compiled_linux_only)), 1)
        flagged_one = {"linux/amd64": lsa.parse_findings(out), "darwin/arm64": set()}
        self.assertEqual(lsa.speculative(flagged_one, compiled), [])  # darwin has a caller


