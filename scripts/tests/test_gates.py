class GateChangedTrailer(unittest.TestCase):
    def test_changed_gate_needs_the_owners_trailer(self):
        root = git_repo({"Makefile": "check:\n", "main.go": "package main\n"})
        env = {"GIT_AUTHOR_NAME": "t", "GIT_AUTHOR_EMAIL": "t@t", "GIT_COMMITTER_NAME": "t",
               "GIT_COMMITTER_EMAIL": "t@t", "PATH": __import__("os").environ["PATH"]}

        def commit(message: str) -> None:
            subprocess.run(["git", "add", "-A"], cwd=root, check=True, env=env)
            subprocess.run(["git", "commit", "-qm", message], cwd=root, check=True, env=env)

        commit("chore: base")
        base = subprocess.run(["git", "rev-parse", "HEAD"], cwd=root, capture_output=True,
                              text=True, check=True).stdout.strip()
        (root / "Makefile").write_text("check:\n\ttrue\n")
        commit("build: loosen the gate")
        cwd = Path.cwd()
        try:
            __import__("os").chdir(root)
            with contextlib.redirect_stdout(io.StringIO()):
                self.assertEqual(tw.check_gates(base, "HEAD"), 1)
                (root / "main.go").write_text("package main\n\n")
                commit("chore: tidy\n\nGate-Changed: owner asked to drop the flaky target")
                self.assertEqual(tw.check_gates(base, "HEAD"), 0)
        finally:
            __import__("os").chdir(cwd)
