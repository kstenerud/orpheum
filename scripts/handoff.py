# ABOUTME: `make handoff`: the state a next session needs, read from the records (decisions' status
# ABOUTME: lines, the verification queue, the debts, git) rather than written from memory (process review F12).
"""The handoff, generated.

A hand-written handoff carried a claim no record held: that D350 needed FFmpeg rebuilt with disc
libraries, against D350's own text, and the lead put it to the owner (2026-10-26). Everything here
is quoted from where it is kept, so a claim in a handoff is the record's claim: each decision not
built, by its own **Status** line; each unticked VQ item; the full check-pr still owed; the code-debt
backlog; the worktrees holding work main lacks; the commits since the owner last applied; and the
standing orders. A session's judgement goes beside it, in its own words, marked as such.
"""

from __future__ import annotations

import re
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DECISIONS = ROOT / "docs" / "contributors" / "decisions" / "working-notes.md"
QUEUE = ROOT / "docs" / "contributors" / "verification-queue.md"
CODE_DEBT = ROOT / "docs" / "contributors" / "code-debt.md"
STANDING_ORDERS = ROOT / ".claude" / "standing-orders.md"
APPLIED_REF = "refs/orpheum/applied"

DECISION = re.compile(r"^## (D\d+) — (.*?)$(.*?)(?=^## D\d+ — |\Z)", re.M | re.S)
STATUS = re.compile(r"^\*\*Status:\*\*\s*(.*)$", re.M)
OPEN_VQ = re.compile(r"^- \[ \] \*\*(VQ\d+)\*\* — (.*)$", re.M)
DEBT_ROW = re.compile(r"^\| (?!Debt |---)(.+?) \|", re.M)


def git(*args: str) -> str:
    done = subprocess.run(["git", *args], cwd=ROOT, capture_output=True, text=True, check=False)
    return done.stdout.strip() if done.returncode == 0 else ""


def unbuilt_decisions(text: str) -> list[str]:
    """Each decision whose own status says it is not built, or is still a reservation, quoted."""
    found = []
    for number, title, body in DECISION.findall(text):
        status = STATUS.search(body)
        said = status.group(1).strip() if status else ""
        if title.startswith("Reserved") or "not built" in said.lower():
            found.append(f"- **{number}** — {title[:110]}  \n  Status: {said or '(none)'}")
    return found


def open_checks(text: str) -> list[str]:
    return [f"- {number} — {what[:120]}" for number, what in OPEN_VQ.findall(text)]


def debts(text: str) -> list[str]:
    return [f"- {row[:140]}" for row in DEBT_ROW.findall(text)]


def worktrees_with_work() -> list[str]:
    """Agent worktrees whose branch holds commits main lacks, or whose tree is dirty."""
    found = []
    for line in git("worktree", "list", "--porcelain").splitlines():
        if not line.startswith("worktree ") or "/.claude/worktrees/" not in line:
            continue
        path = line.removeprefix("worktree ")
        ahead = git("-C", path, "rev-list", "--count", "main..HEAD") or "?"
        dirty = len(git("-C", path, "status", "--porcelain").splitlines())
        if ahead != "0" or dirty:
            found.append(f"- `{path}`: {ahead} commit(s) main lacks, {dirty} uncommitted file(s)")
    return found


def section(title: str, lines: list[str], empty: str) -> str:
    return f"## {title}\n\n" + ("\n".join(lines) if lines else empty) + "\n"


def read(path: Path) -> str:
    return path.read_text(encoding="utf-8") if path.exists() else ""


def handoff() -> str:
    head = git("log", "-1", "--format=%h %s")
    applied = git("rev-parse", "--verify", "--quiet", APPLIED_REF)
    unapplied = git("log", "--format=- %h %s", f"{applied}..HEAD") if applied else ""
    owed = subprocess.run([sys.executable, str(ROOT / "scripts" / "check_pr_debt.py"), "show"], cwd=ROOT,
                          capture_output=True, text=True, check=False).stdout.strip()
    parts = [
        "# Handoff (generated by `make handoff`: every line is quoted from its record)\n",
        f"HEAD: {head}\n",
        section("Standing orders", [read(STANDING_ORDERS).strip()], "(none)"),
        section("Commits since the owner last applied",
                unapplied.splitlines() if applied else [],
                "(no applied mark: run `make mark-applied` after `yoloai apply`)" if not applied else "(none)"),
        section("Owed", [owed] if owed else [], "Nothing owed."),
        section("Decisions not built (their own status lines)", unbuilt_decisions(read(DECISIONS)), "(none)"),
        section("Worktrees holding work main lacks", worktrees_with_work(), "(none)"),
        section("Device checks still open (verification-queue.md)", open_checks(read(QUEUE)), "(none)"),
        section("Code debt (code-debt.md)", debts(read(CODE_DEBT)), "(none)"),
    ]
    return "\n".join(parts)


if __name__ == "__main__":
    print(handoff())
